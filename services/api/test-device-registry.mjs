import assert from "node:assert/strict";
import crypto from "node:crypto";
import {DeviceRegistry,derivePin} from "./src/device-registry.mjs";
let now=Date.now();
const registry=new DeviceRegistry({clock:()=>now});
const keys=crypto.generateKeyPairSync("ed25519",{publicKeyEncoding:{type:"spki",format:"pem"},privateKeyEncoding:{type:"pkcs8",format:"pem"}});
const other=crypto.generateKeyPairSync("ed25519",{publicKeyEncoding:{type:"spki",format:"pem"},privateKeyEncoding:{type:"pkcs8",format:"pem"}});
const {pin,challenge}=registry.challenge(keys.publicKey);
assert.equal(pin,derivePin(keys.publicKey));
assert.equal(registry.lookup(pin),null);
const signature=crypto.sign(null,Buffer.from(challenge),crypto.createPrivateKey(keys.privateKey)).toString("base64url");
assert.throws(()=>registry.register({publicKey:keys.publicKey,challenge,signature:"invalid"}));
assert.throws(()=>registry.register({publicKey:keys.publicKey,challenge,signature}));
const next=registry.challenge(keys.publicKey);
const badSignature=crypto.sign(null,Buffer.from(next.challenge),crypto.createPrivateKey(other.privateKey)).toString("base64url");
assert.throws(()=>registry.register({publicKey:keys.publicKey,challenge:next.challenge,signature:badSignature}));
const third=registry.challenge(keys.publicKey);
const valid=crypto.sign(null,Buffer.from(third.challenge),crypto.createPrivateKey(keys.privateKey)).toString("base64url");
assert.deepEqual(registry.register({publicKey:keys.publicKey,challenge:third.challenge,signature:valid}),{pin,registered:true});
assert.equal(registry.lookup(pin)?.publicKey,keys.publicKey);
assert.throws(()=>registry.register({publicKey:keys.publicKey,challenge:third.challenge,signature:valid}));
const expired=registry.challenge(other.publicKey);
now+=61_000;
assert.throws(()=>registry.register({publicKey:other.publicKey,challenge:expired.challenge,signature:crypto.sign(null,Buffer.from(expired.challenge),crypto.createPrivateKey(other.privateKey)).toString("base64url")}));
const sessionChallenge=registry.challenge(keys.publicKey,"session");
const sessionSignature=crypto.sign(null,Buffer.from(sessionChallenge.challenge),crypto.createPrivateKey(keys.privateKey)).toString("base64url");
const session=registry.authenticate({publicKey:keys.publicKey,challenge:sessionChallenge.challenge,signature:sessionSignature});
assert.equal(session.pin,pin);
assert.equal(registry.authorize(session.accessToken)?.pin,pin);
assert.equal(registry.authorize("invalid"),null);
assert.throws(()=>registry.authenticate({publicKey:keys.publicKey,challenge:sessionChallenge.challenge,signature:sessionSignature}));
const crossPurpose=registry.challenge(keys.publicKey,"session");
const crossSignature=crypto.sign(null,Buffer.from(crossPurpose.challenge),crypto.createPrivateKey(keys.privateKey)).toString("base64url");
assert.throws(()=>registry.register({publicKey:keys.publicKey,challenge:crossPurpose.challenge,signature:crossSignature}));
now+=901_000;
assert.equal(registry.authorize(session.accessToken),null);
console.log("ZERO device registry and session tests passed");

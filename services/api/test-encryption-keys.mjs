import assert from "node:assert/strict";
import crypto from "node:crypto";
import {DeviceRegistry,derivePin} from "./src/device-registry.mjs";
const registry=new DeviceRegistry({});
const identity=crypto.generateKeyPairSync("ed25519");
const identityPublic=identity.publicKey.export({type:"spki",format:"pem"}).toString();
const pin=derivePin(identityPublic);
const challenge=registry.challenge(identityPublic);
const signature=crypto.sign(null,Buffer.from(challenge.challenge),identity.privateKey).toString("base64url");
registry.register({publicKey:identityPublic,challenge:challenge.challenge,signature});
const encryption=crypto.generateKeyPairSync("x25519");
const publicKey=encryption.publicKey.export({type:"spki",format:"pem"}).toString();
const statement="ZERO-ENCRYPTION-KEY-V1|"+pin+"|"+publicKey;
const proof=crypto.sign(null,Buffer.from(statement),identity.privateKey).toString("base64url");
assert.throws(()=>registry.publishEncryptionKey(pin,publicKey,"invalid"));
assert.deepEqual(registry.publishEncryptionKey(pin,publicKey,proof),{published:true,pin});
assert.equal(registry.lookupEncryptionKey(pin).publicKey,publicKey);
assert.equal(registry.lookupEncryptionKey(pin).signature,proof);
assert.deepEqual(registry.publishEncryptionKey(pin,publicKey,proof),{published:true,pin});
const replacement=crypto.generateKeyPairSync("x25519").publicKey.export({type:"spki",format:"pem"}).toString();
const replacementProof=crypto.sign(null,Buffer.from("ZERO-ENCRYPTION-KEY-V1|"+pin+"|"+replacement),identity.privateKey).toString("base64url");
assert.throws(()=>registry.publishEncryptionKey(pin,replacement,replacementProof));
assert.equal(registry.lookupEncryptionKey("ABCD-EFGH-JKLM-NPQR"),null);
console.log("ZERO signed encryption key registry tests passed");

import assert from "node:assert/strict";
import crypto from "node:crypto";
import {MessageRelay} from "./src/message-relay.mjs";
const relay=new MessageRelay({maxPerRecipient:1});
const a="ABCD-EFGH-JKLM-NPQR",b="STUV-WXYZ-2345-6789";
const ephemeral=crypto.generateKeyPairSync("x25519").publicKey.export({type:"spki",format:"pem"}).toString();
const encrypted={algorithm:"x25519-hkdf-aes256gcm-v1",ephemeralPublicKey:ephemeral,salt:"A".repeat(43),nonce:"A".repeat(16),ciphertext:"B".repeat(40)};
assert.throws(()=>relay.send(a,b,{...encrypted,plaintext:"hello"}));
assert.throws(()=>relay.send(a,b,{...encrypted,algorithm:"none"}));
assert.throws(()=>relay.send(a,b,{...encrypted,ephemeralPublicKey:"not a key"}));
const sent=relay.send(a,b,encrypted);
assert.equal(sent.queued,true);
const inbox=relay.inbox(b);
assert.equal(inbox.length,1);
assert.equal(inbox[0].sender,a);
assert.equal(inbox[0].encrypted.ciphertext,encrypted.ciphertext);
assert.equal(JSON.stringify(inbox).includes("plaintext"),false);
assert.throws(()=>relay.send(a,b,encrypted));
assert.deepEqual(relay.acknowledge(b,sent.id),{acknowledged:true});
assert.equal(relay.inbox(b).length,0);
assert.deepEqual(relay.acknowledge(b,sent.id),{acknowledged:false});
let now=Date.now();
const temporary=new MessageRelay({clock:()=>now});
assert.throws(()=>temporary.send(a,b,encrypted,9));
assert.throws(()=>temporary.send(a,b,encrypted,604801));
temporary.send(a,b,encrypted,10);
assert.equal(temporary.inbox(b).length,1);
now+=10001;
assert.equal(temporary.inbox(b).length,0);
const defaultExpiry=new MessageRelay({clock:()=>now});
defaultExpiry.send(a,b,encrypted);
now+=24*60*60*1000+1;
assert.equal(defaultExpiry.inbox(b).length,0);
console.log("ZERO opaque relay and expiry tests passed");
